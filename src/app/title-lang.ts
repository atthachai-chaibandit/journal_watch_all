/**
 * ตรวจว่าชื่อบทความกรอกถูกช่องภาษา (ใช้ทั้งฟอร์ม Pre-T3 และ T3)
 * - ช่องอังกฤษ: ห้ามมีอักษรไทย
 * - ช่องไทย: ต้องมีอักษรไทยอย่างน้อย 1 ตัว — ไม่ห้ามอักษรอังกฤษ เพราะชื่อไทยมักมีศัพท์อังกฤษปน เช่น "การพัฒนาระบบ IoT"
 * ค่าว่างผ่านเสมอ (เรื่องบังคับกรอกให้แต่ละฟอร์มเช็คเอง)
 */
const THAI_CHAR = /[฀-๿]/;

export function englishTitleError(value: string): string {
  return THAI_CHAR.test(value) ? 'ช่องนี้เป็นชื่อบทความภาษาอังกฤษ — ห้ามมีตัวอักษรภาษาไทย' : '';
}

export function thaiTitleError(value: string): string {
  const v = value.trim();
  return v && !THAI_CHAR.test(v) ? 'ช่องนี้เป็นชื่อบทความภาษาไทย — ต้องมีตัวอักษรภาษาไทย (มีคำภาษาอังกฤษปนได้)' : '';
}
